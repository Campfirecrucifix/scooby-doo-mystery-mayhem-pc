pub static MODULE: ModuleDef = ModuleDef {
    name: "wisps",
    // largest build: l03a_wisps__44cbb300, gpoLanguagesNamesAndISOCodes ends at 0x104d2
    data_size: 0x4d8,
    ctor: wisps_levelConstructor,
    dtor: wisps_levelDestructor,
    register: None,
    init: &[],
    build_init: Some(wisps_build_init),
};

/// Index of a build in [`builds::BUILDS`] by its directory name (`l01_wisps`) or SHA-1 prefix.
pub fn build_index(sha8: &str) -> Option<usize> {
    builds::BUILDS.iter().position(|b| b.sha8 == sha8)
}

/// the initialised part of the image: `TmpWispMap`
fn wisps_build_init(m: &mut Mem, data: Ptr, build: usize) {
    for (i, &w) in maps::TMP_WISP_MAP[build].iter().enumerate() {
        m.w32(data + (TmpWispMap - 0x10000) + i as u32 * 4, w);
    }
}


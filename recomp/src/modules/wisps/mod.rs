//! `lNN_wisps`: the glowing orbs (wisps) that refill the Tome of Doom's power. One module per level
//! pack (21 builds under `Game Logic Modules/Globals/Collectables/Wisp/l*_wisps*`, 59 functions in
//! the reference build `l01_wisps`): a wisp bobs in place, is picked up by touch or sucked in by the
//! open book, adds 18/36/54 to the book power (game buffer 1 +4, capped at 180) and plays the
//! collect sparkles through the GENERIC_FX latent object.
//!
//! The builds differ in:
//! - `TmpWispMap` (0x10038): the level's wisps, N records of 0x24 bytes ([`maps`], generated). The
//!   module globals after it move with N: they start at `align8(0x10038 + N * 0x24)` ([`X`]).
//! - the global data layout (size, offsets of the arrays sized by N) and object ids: per-build
//!   literals [`builds`] (`k(e, NAME)`), generated by gen_builds.py.
//! - InitWispData without loop when N = 0 and Init_LocalSetting without loop when N = 1 (shape groups).
//! - two levels add functions: l03a_wisps__44cbb300 (cut-scene callback, message 0xe7) and
//!   l04_wisps__ed7e7a13 (message 0xc9 kills the launched wisps). See [`level`].
//!
//! State functions are stored as code pointers at local data +0 in the original. The port stores the
//! reference build's module-relative address (the same for every build here; the original's values
//! differ per build but are only ever called, never compared) and dispatches in `call_state`.

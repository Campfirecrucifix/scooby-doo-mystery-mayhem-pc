/// module-relative address of `uiToStatusPointerMapWisp`; `pLocalDataWisp_base` and
/// `pGlobalDataWisp_base` follow at +4 and +8
#[inline]
pub(crate) fn X(e: &Engine) -> u32 {
    (TmpWispMap + maps::TMP_WISP_MAP[e.rt.cur_build()].len() as u32 * 4 + 7) & !7
}
/// address of a module global
#[inline]
pub(crate) fn G(e: &Engine, a: u32) -> Ptr {
    e.rt.cur_data() + (a - 0x10000)
}
/// &uiToStatusPointerMapWisp
#[inline]
pub(crate) fn uiToStatusPointerMapWisp(e: &Engine) -> Ptr {
    G(e, X(e))
}
/// &pLocalDataWisp_base
#[inline]
pub(crate) fn pLocalDataWisp_base(e: &Engine) -> Ptr {
    G(e, X(e) + 4)
}
/// &pGlobalDataWisp_base
#[inline]
pub(crate) fn pGlobalDataWisp_base(e: &Engine) -> Ptr {
    G(e, X(e) + 8)
}
/// current value of `pLocalDataWisp_base`
#[inline]
pub(crate) fn L(e: &Engine) -> Ptr {
    e.r32(pLocalDataWisp_base(e))
}
/// current value of `pGlobalDataWisp_base`
#[inline]
pub(crate) fn GD(e: &Engine) -> Ptr {
    e.r32(pGlobalDataWisp_base(e))
}
/// per-build literal
#[inline]
pub(crate) fn k(e: &Engine, i: usize) -> u32 {
    builds::BUILDS[e.rt.cur_build()].k[i]
}
/// per-build shape group
#[inline]
pub(crate) fn g(e: &Engine, i: usize) -> u8 {
    builds::BUILDS[e.rt.cur_build()].g[i]
}
/// `*(float *)(*(int *)(pGlobalDataWisp_base + 8) + 4)`: the book power (game buffer 1 +4)
#[inline]
pub(crate) fn power(e: &Engine) -> Ptr {
    e.r32(GD(e) + 8) + 4
}

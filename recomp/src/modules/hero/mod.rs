//! `hero`: Scooby and Shaggy (the player characters). One shared C source (`hero_*.c`) compiled per
//! character (`scooby.c` / `shaggy.c` + `#ifdef`ed parts) and per level pack. Port of
//! `Game Logic Modules/<Episode>/Characters/{Scooby,Shaggy}/<Level>/<scooby|shaggy>__<sha8>/`.
//! Reference build: scooby__402420b4 (EP1L01 Scooby).
//!
//! Family: the 57 builds that contain the book code (hero_tome.c), listed in
//! `tools/rustport/hero_family.txt`. The 33 others (costume heroes such as scooby_ghost or
//! shaggy_cowboy, and 4 plain builds) have no Tome of Doom code and are not part of this port yet.
//! Every function differs only in literals inside a shape group, see [`builds`] (generated by
//! tools/rustport/gen_builds.py over hero_family.txt). The four main shape groups are the two
//! characters times two source revisions: 402420b4 = Scooby (23 builds), 2b32b17e = older Scooby
//! (6), 0117f115 = Shaggy (24), 1730c849 = older Shaggy (4).
//!
//! PORT STATUS: book-related functions are ported (see PORT_NOTES.md "Step 5"). The rest of this
//! module is generated stubs that `todo!()` with the function's name. Nothing is silently skipped:
//! calling an unported function panics with that name.
//!
//! The module's globals are shared by every instance (the engine swaps `pLocalDataHero` per
//! instance), exactly as on the PS2; they live in the module data image.
#![allow(non_snake_case, non_upper_case_globals, unused_variables, unused_mut, unused_assignments)]
